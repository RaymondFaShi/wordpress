/**
 * Create or update the footer guide and policy pages once per content version.
 */
function vk_sync_footer_pages() {
	$version = '2026-11-06-1';
	if ( get_option( 'vk_footer_pages_version' ) === $version ) {
		return;
	}

	foreach ( vk_footer_page_definitions() as $slug => $definition ) {
		$existing = get_page_by_path( $slug );
		$data     = array(
			'post_title'   => $definition['title'],
			'post_content' => wp_kses_post( $definition['content'] ),
			'post_status'  => 'publish',
			'post_type'    => 'page',
		);
		if ( $existing instanceof WP_Post ) {
			$data['ID'] = $existing->ID;
			$page_id    = wp_update_post( $data, true );
		} else {
			$data['post_name'] = $slug;
			$page_id           = wp_insert_post( $data, true );
		}
		if ( ! is_wp_error( $page_id ) && 'privacy' === $slug ) {
			update_option( 'wp_page_for_privacy_policy', (int) $page_id );
		}
	}

	update_option( 'vk_footer_pages_version', $version, false );
	flush_rewrite_rules( false );
}
add_action( 'init', 'vk_sync_footer_pages', 35 );

